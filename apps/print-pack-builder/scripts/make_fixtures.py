#!/usr/bin/env python3
"""Generate the synthetic demo/test fixtures for the Print Pack Builder.

These are invented sample pages, not Little Chewz worksheets. Output is a
TypeScript module of base64 strings so the Worker and the tests share the
same bytes without any file-system or asset binding.

Usage (from apps/print-pack-builder):  python3 scripts/make_fixtures.py
Needs reportlab and Pillow (already in the repository requirements.txt).
"""
import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw
from reportlab.lib.pagesizes import A4, letter
from reportlab.pdfgen import canvas

OUT = Path(__file__).resolve().parents[1] / "worker" / "demo" / "fixtures.generated.ts"
CORAL = (0.93, 0.42, 0.36)
INK = (0.2, 0.2, 0.25)


def pdf(pages, size=letter, cards=None):
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=size, invariant=1)
    w, h = size
    for n, title in enumerate(pages, 1):
        if cards:
            cw, ch = w / 2, h / 2
            for i in range(cards):
                x, y = (i % 2) * cw, h - (i // 2 + 1) * ch
                c.setStrokeColorRGB(*INK)
                c.setDash(4, 4)
                c.rect(x + 12, y + 12, cw - 24, ch - 24)
                c.setDash()
                c.setFillColorRGB(*CORAL)
                c.setFont("Helvetica-Bold", 18)
                c.drawCentredString(x + cw / 2, y + ch - 60, title)
                c.setFillColorRGB(*INK)
                c.setFont("Helvetica", 12)
                c.drawCentredString(x + cw / 2, y + ch / 2, f"Card {i + 1} of {cards} on this sheet")
        else:
            c.setFillColorRGB(*CORAL)
            c.setFont("Helvetica-Bold", 28)
            c.drawString(54, h - 90, title)
            c.setFillColorRGB(*INK)
            c.setFont("Helvetica", 12)
            c.drawString(54, h - 115, f"Synthetic demo page {n} of {len(pages)}. Not a Little Chewz worksheet.")
            c.drawString(54, h - 150, "Name: ______________________    Date: ____________")
            c.setStrokeColorRGB(0.8, 0.8, 0.82)
            for y in range(int(h - 200), 80, -28):
                c.line(54, y, w - 54, y)
        c.showPage()
    c.save()
    return buf.getvalue()


def image(size, title, fmt):
    img = Image.new("RGB", size, (255, 249, 240))
    d = ImageDraw.Draw(img)
    w, h = size
    d.rectangle([20, 20, w - 20, h - 20], outline=(237, 107, 92), width=8)
    d.rectangle([60, 60, w - 60, 160], fill=(237, 107, 92))
    d.text((80, 95), title, fill=(255, 255, 255))
    d.text((80, 190), "Synthetic demo image. Not a Little Chewz worksheet.", fill=(50, 50, 60))
    for y in range(260, h - 60, 50):
        d.line([80, y, w - 80, y], fill=(200, 200, 205), width=2)
    out = io.BytesIO()
    if fmt == "PNG":
        img = img.convert("P", palette=Image.ADAPTIVE, colors=16)
        img.save(out, "PNG", optimize=True)
    else:
        img.save(out, "JPEG", quality=70)
    return out.getvalue()


FIXTURES = {
    "reading-log.pdf": pdf(["Sample Reading Log", "Sample Reading Log (continued)"]),
    "exit-ticket.pdf": pdf(["Sample Exit Ticket"], size=A4),
    "team-cards.pdf": pdf(["Team Challenge"], cards=4),
    "station-poster.png": image((850, 1100), "Sample Station Poster (PNG)", "PNG"),
    "photo-prompt.jpg": image((1100, 850), "Sample Photo Prompt (JPEG, landscape)", "JPEG"),
}

lines = [
    "// Generated by scripts/make_fixtures.py. Do not edit. Synthetic demo files only.",
    "export const FIXTURES: Record<string, string> = {",
]
for name, data in FIXTURES.items():
    lines.append(f'  "{name}": "{base64.b64encode(data).decode()}",')
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
for name, data in FIXTURES.items():
    print(f"{name}: {len(data)} bytes")
